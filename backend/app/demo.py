def art_url(title: str) -> str:
    from urllib.parse import quote
    t = title.lower()
    for word, emoji, hue in ART:
        if word in t:
            break
    else:
        emoji, hue = "🍽️", 25
    slug = "".join(ch if ch.isalnum() else "-" for ch in t)[:40]
    return f"/art/{quote(slug)}.svg?e={quote(emoji)}&h={hue}"
