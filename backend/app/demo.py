def build(row) -> Recipe:
    title, desc, cuisine, meal, serv, prep, cook, tags, collection, ings, steps = row
    return Recipe(
        id=uuid.uuid4().hex, is_recipe=True, title=title, description=desc, cuisine=cuisine, meal_type=meal,
        servings=serv, prep_minutes=prep or None, cook_minutes=cook or None, total_minutes=(prep or 0) + (cook or 0) or None,
        tags=tags, confidence=1.0, source_url="", source_platform="gohan", author="Gohan",
        ingredients=[Ingredient(quantity=q or None, unit=u or None, name=n, note=no) for q, u, n, no in ings],
        steps=[Step(text=s) if isinstance(s, str) else Step(text=s[0], bimby=BimbySetting(**s[1])) for s in steps],
        created_at=now(),
    )


def seed(store, username: str, share: bool = True) -> tuple[int, int]:
    """Add the demo recipes for one person; returns (added, skipped)."""
    import json
    user = store.one("SELECT id FROM users WHERE username=?", (username,))
    if not user:
        raise SystemExit(f"Não existe o utilizador '{username}'. Cria a conta primeiro.")
    uid = user["id"]
    have = {r["title"] for r in store.q("SELECT title FROM recipes WHERE owner_id=?", (uid,))}
    groups = [r["group_id"] for r in store.q("SELECT group_id FROM members WHERE user_id=?", (uid,))] if share else []
    added = 0
    for row in RECIPES:
        rec = build(row)
        if rec.title in have:
            continue
        store.save_recipe(rec, uid)
        store.x("INSERT OR REPLACE INTO user_recipe(user_id, recipe_id, favorite, collections) VALUES (?,?,0,?)",
                (uid, rec.id, json.dumps([row[8]], ensure_ascii=False)))
        for gid in groups:
            store.x("INSERT OR IGNORE INTO recipe_shares(recipe_id, group_id, shared_by, shared_at) VALUES (?,?,?,?)",
                    (rec.id, gid, uid, now()))
        added += 1
    return added, len(RECIPES) - added
