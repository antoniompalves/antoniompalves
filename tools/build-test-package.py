#!/usr/bin/env python3
"""
Build a TEST package of the site for a subfolder on cPanel (e.g. https://eqtraining.pt/teste/).

Included: home, about, contact (with the Damiana popup and its form), the first programme
(Inteligência Emocional) and the privacy policy (linked from the form consent), in PT and EN.
Everything else (services, programmes list, the app programme, press, blog) is switched off
through config.php, and links to it are hidden. Search engines are blocked (noindex + robots.txt).

Usage (from the repo root):
    python3 tools/build-test-package.py            # folder "teste"
    python3 tools/build-test-package.py beta       # any other folder name
Output: dist/eqtraining-<folder>.zip — unzip into public_html/<folder>/
"""
import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "public"
FOLDER = (sys.argv[1] if len(sys.argv) > 1 else "teste").strip("/")
if not re.fullmatch(r"[a-z0-9_-]+", FOLDER):
    sys.exit("Folder name: lowercase letters, digits, - or _ only")

DIST = ROOT / "dist"
STAGE = DIST / "build" / FOLDER

# What the test build does not need
DROP = [
    "templates/services.php", "templates/press.php", "templates/blog.php", "templates/post.php",
    "templates/courses.php", "templates/programme.php", "templates/partials/ecosystem.php",
    "content/app-programme.php", "content/post-meta.php", "content/consulting.php", "content/press.php",
    "assets/img/blog", "assets/img/app", "assets/img/programmes", "assets/img/press",
]

CONFIG_EXTRA = f"""    'base_url'       => '/{FOLDER}',                  // TEST build: site lives in /{FOLDER}/

    // ---- TEST build (generated by tools/build-test-package.py) ----
    'noindex'        => true,                                  // keep search engines out
    'pages'          => ['home', 'about', 'contact', 'privacy', 'courses'],
    'courses_list'   => false,                                 // no programmes list: "Programas" opens the first programme
    'course_ids'     => ['ie'],                                // only "Inteligência Emocional para Equipas e Líderes"
"""

HTACCESS = f"""# EQTraining.pt — TEST build in /{FOLDER}/ (Apache / cPanel)
Options -Indexes
DirectoryIndex index.php

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /{FOLDER}/

  # Force HTTPS (uncomment if the domain has SSL)
  # RewriteCond %{{HTTPS}} off
  # RewriteRule ^ https://%{{HTTP_HOST}}%{{REQUEST_URI}} [L,R=301]

  # Block direct access to internals
  RewriteRule ^(config\\.php|includes|lang|content|templates|storage)(/|$) - [F,L]

  # Add trailing slash to page URLs (not files, not the form endpoint)
  RewriteCond %{{REQUEST_FILENAME}} !-f
  RewriteCond %{{REQUEST_URI}} !/$
  RewriteCond %{{REQUEST_URI}} !/api/
  RewriteCond %{{REQUEST_URI}} !\\.[a-zA-Z0-9]{{2,5}}$
  RewriteRule ^(.*)$ /{FOLDER}/$1/ [L,R=301]

  # Everything that is not a real file goes to the front controller
  RewriteCond %{{REQUEST_FILENAME}} !-f
  RewriteCond %{{REQUEST_FILENAME}} !-d
  RewriteRule ^ index.php [L,QSA]
</IfModule>

<IfModule mod_headers.c>
  Header set X-Robots-Tag "noindex, nofollow"
  Header set X-Content-Type-Options "nosniff"
  Header set Referrer-Policy "strict-origin-when-cross-origin"
  Header set X-Frame-Options "SAMEORIGIN"
</IfModule>

AddType video/mp4 .mp4
AddType image/svg+xml .svg
"""

README = f"""EQ TRAINING — PACOTE DE TESTE
=============================

Conteúdo: página inicial, Sobre, Contactos (com o formulário), popup da Damiana (com o formulário),
o programa "Inteligência Emocional para Equipas e Líderes" e a Política de Privacidade
(necessária porque o formulário tem o consentimento ligado a ela). Em português e inglês.
As outras páginas (Serviços, lista de Programas, Formação com App, Imprensa, Blog) estão
desligadas e os links para elas escondidos. O Google não indexa esta pasta.

COMO INSTALAR (cPanel)
1. Gestor de Ficheiros > public_html > criar a pasta "{FOLDER}".
2. Carregar o ZIP para dentro de public_html/{FOLDER}/ e escolher "Extrair".
   Os ficheiros (index.php, .htaccess, assets, …) têm de ficar diretamente em public_html/{FOLDER}/.
3. Ativar a visualização de ficheiros ocultos para confirmar que o .htaccess está lá.
4. Abrir https://SEU-DOMINIO/{FOLDER}/

FORMULÁRIOS
- Os pedidos seguem por email para o endereço em config.php ('email_to') e ficam também
  guardados em storage/leads.csv. Confirme que 'email_from' é uma caixa de email desse domínio.

OPCIONAL
- Para só a equipa ver a pasta: cPanel > Privacidade de Diretórios > public_html/{FOLDER} > proteger com palavra-passe.
- Se mudar o nome da pasta, gere o pacote outra vez:  python3 tools/build-test-package.py novo-nome
"""


def main() -> None:
    if STAGE.exists():
        shutil.rmtree(STAGE)
    shutil.copytree(SRC, STAGE, ignore=shutil.ignore_patterns(".DS_Store", "*.csv"))

    for rel in DROP:
        p = STAGE / rel
        if p.is_dir():
            shutil.rmtree(p)
        elif p.exists():
            p.unlink()
    # Blog content is not part of the test (keeps the package light)
    (STAGE / "content/posts.php").write_text("<?php\n// Blog is switched off in the test build.\nreturn [];\n", encoding="utf-8")

    cfg = (STAGE / "config.php").read_text(encoding="utf-8")
    cfg, n = re.subn(r"^\s*'base_url'\s*=>.*\n", CONFIG_EXTRA, cfg, count=1, flags=re.M)
    if n != 1:
        sys.exit("Could not find 'base_url' in config.php")
    (STAGE / "config.php").write_text(cfg, encoding="utf-8")

    (STAGE / ".htaccess").write_text(HTACCESS, encoding="utf-8")
    man = STAGE / "site.webmanifest"
    man.write_text(man.read_text(encoding="utf-8").replace('"/assets/', f'"/{FOLDER}/assets/'), encoding="utf-8")
    (STAGE / "storage").mkdir(exist_ok=True)
    (STAGE / "LEIA-ME-TESTE.txt").write_text(README, encoding="utf-8")

    zpath = DIST / f"eqtraining-{FOLDER}.zip"
    if zpath.exists():
        zpath.unlink()
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(STAGE.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(STAGE).as_posix())
    files = sum(1 for f in STAGE.rglob("*") if f.is_file())
    print(f"{zpath.relative_to(ROOT)}  ({zpath.stat().st_size / 1e6:.1f} MB, {files} files)")


if __name__ == "__main__":
    main()
