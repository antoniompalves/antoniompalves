#!/usr/bin/env python3
"""
Build a TEST package of the site that works in ANY subfolder on cPanel
(e.g. https://example.com/teste/ or /eqtraining/); the folder is detected automatically.

Included: home, about, contact (with the Damiana popup and its form), the first programme
(Inteligência Emocional), the blog and the privacy policy (linked from the form consent), in PT and EN.
Everything else (services, programmes list, the app programme, press) is switched off through
config.php: those menu items stay visible without a link, other links to them are hidden. Search engines are blocked (noindex + robots.txt).

Usage (from the repo root):
    python3 tools/build-test-package.py
Output: dist/eqtraining-teste.zip — unzip into any folder, e.g. public_html/eqtraining/
"""
import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "public"
FOLDER = "teste"   # only names the zip; the site detects its folder at runtime

DIST = ROOT / "dist"
STAGE = DIST / "build" / FOLDER

# What the test build does not need
DROP = [
    "templates/services.php", "templates/press.php",
    "templates/courses.php", "templates/programme.php", "templates/partials/ecosystem.php",
    "content/app-programme.php", "content/consulting.php", "content/press.php",
    "content/programmes/stress.php", "content/programmes/conflict.php",
    "content/programmes/behaviour.php", "content/programmes/decision.php",
    "assets/img/app", "assets/img/press",
    "assets/img/programmes/stress.webp", "assets/img/programmes/conflitos.webp", "assets/img/programmes/comportamental.webp",
]

CONFIG_EXTRA = f"""    'base_url'       => 'auto',                      // TEST build: detects the folder it is installed in

    // ---- TEST build (generated by tools/build-test-package.py) ----
    'noindex'        => true,                                  // keep search engines out
    'pages'          => ['home', 'about', 'contact', 'privacy', 'courses', 'blog'],
    'courses_list'   => false,                                 // no programmes list: "Programas" opens the first programme
    'course_ids'     => ['ie'],                                // only "Inteligência Emocional para Equipas e Líderes"
"""

HTACCESS = f"""# EQTraining.pt — TEST build, works in any folder (Apache / cPanel)
Options -Indexes
DirectoryIndex index.php

<IfModule mod_rewrite.c>
  RewriteEngine On

  # Force HTTPS (uncomment if the domain has SSL)
  # RewriteCond %{{HTTPS}} off
  # RewriteRule ^ https://%{{HTTP_HOST}}%{{REQUEST_URI}} [L,R=301]

  # Block direct access to internals
  RewriteRule ^(config\\.php|includes|lang|content|templates|storage)(/|$) - [F,L]

  # Add trailing slash to page URLs (not files, not the form endpoint)
  RewriteCond %{{REQUEST_FILENAME}} !-f
  RewriteCond %{{REQUEST_URI}} !/$
  RewriteCond %{{REQUEST_URI}} !/api/
  RewriteCond %{{REQUEST_URI}} !\\.[a-zA-Z0-9]{{2,5}}$
  RewriteRule ^ %{{REQUEST_URI}}/ [L,R=301]

  # Everything that is not a real file goes to the front controller
  RewriteCond %{{REQUEST_FILENAME}} !-f
  RewriteCond %{{REQUEST_FILENAME}} !-d
  RewriteRule ^ index.php [L,QSA]
</IfModule>

<IfModule mod_headers.c>
  Header set X-Robots-Tag "noindex, nofollow"
  Header set X-Content-Type-Options "nosniff"
  Header set Referrer-Policy "strict-origin-when-cross-origin"
  Header set X-Frame-Options "SAMEORIGIN"
</IfModule>

AddType video/mp4 .mp4
AddType image/svg+xml .svg
"""

README = f"""EQ TRAINING — PACOTE DE TESTE
=============================

Conteúdo: página inicial, Sobre, Contactos (com o formulário), popup da Damiana (com o formulário),
o programa "Inteligência Emocional para Equipas e Líderes" (com a estrutura de 8 secções comum
a todos os programas e o formulário de pedido de proposta), o Blog e a Política de Privacidade
(necessária porque o formulário tem o consentimento ligado a ela). Em português e inglês.
Serviços e Imprensa aparecem no menu mas ainda sem link; a lista de Programas e a Formação com App
estão desligadas. O Google não indexa esta pasta.

COMO INSTALAR (cPanel) — funciona em qualquer pasta (ex.: eqtraining, teste)
1. Gestor de Ficheiros > public_html > criar a pasta (ex.: "eqtraining").
2. Carregar o ZIP para dentro dessa pasta e escolher "Extrair".
   Os ficheiros (index.php, .htaccess, assets, …) têm de ficar diretamente dentro da pasta,
   não numa subpasta extra.
3. Em Definições do Gestor de Ficheiros, ativar "Mostrar ficheiros ocultos" e confirmar que o .htaccess está lá.
4. Abrir https://SEU-DOMINIO/NOME-DA-PASTA/

FORMULÁRIOS
- Os pedidos seguem por email para o endereço em config.php ('email_to') e ficam também
  guardados em storage/leads.csv. Confirme que 'email_from' é uma caixa de email desse domínio.

OPCIONAL
- Para só a equipa ver a pasta: cPanel > Privacidade de Diretórios > a pasta > proteger com palavra-passe.
- Ao substituir uma versão anterior, apague primeiro os ficheiros antigos da pasta (incluindo o .htaccess).
"""


def main() -> None:
    if STAGE.exists():
        shutil.rmtree(STAGE)
    shutil.copytree(SRC, STAGE, ignore=shutil.ignore_patterns(".DS_Store", "*.csv"))

    for rel in DROP:
        p = STAGE / rel
        if p.is_dir():
            shutil.rmtree(p)
        elif p.exists():
            p.unlink()

    cfg = (STAGE / "config.php").read_text(encoding="utf-8")
    cfg, n = re.subn(r"^\s*'base_url'\s*=>.*\n", CONFIG_EXTRA, cfg, count=1, flags=re.M)
    if n != 1:
        sys.exit("Could not find 'base_url' in config.php")
    (STAGE / "config.php").write_text(cfg, encoding="utf-8")

    (STAGE / ".htaccess").write_text(HTACCESS, encoding="utf-8")
    (STAGE / "storage").mkdir(exist_ok=True)
    (STAGE / "LEIA-ME-TESTE.txt").write_text(README, encoding="utf-8")

    zpath = DIST / f"eqtraining-{FOLDER}.zip"
    if zpath.exists():
        zpath.unlink()
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(STAGE.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(STAGE).as_posix())
    files = sum(1 for f in STAGE.rglob("*") if f.is_file())
    print(f"{zpath.relative_to(ROOT)}  ({zpath.stat().st_size / 1e6:.1f} MB, {files} files)")


if __name__ == "__main__":
    main()
